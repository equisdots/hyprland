#!/usr/bin/env bash
# check_sh_test.sh — tests scripts/check.sh without touching the real config.
#
# Covers the two supported layouts (repo checkout vs deployed ~/.config/hypr),
# the fake-Hyprland result propagation, and the missing-binary skip path.

set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

fail=0
ok()  { printf ' ok   %s\n' "$*"; }
bad() { printf ' FAIL %s\n' "$*"; fail=1; }

BIN="$TMP/bin"
mkdir -p "$BIN"
cat > "$BIN/Hyprland" <<'FAKE'
#!/usr/bin/env bash
printf '%s\n' "${HYPRLAND_CONFIG:-}" >> "${HYPR_TEST_LOG:?}"
config="${HYPRLAND_CONFIG:-}"
[ -f "$config" ] || { echo "fake Hyprland: missing $config" >&2; exit 1; }
if grep -q 'FAIL' "$config"; then
    echo "fake Hyprland: invalid config" >&2
    exit 1
fi
echo "config ok"
FAKE
chmod +x "$BIN/Hyprland"

setup_layout() {
    local dir="$1" mode="$2"
    mkdir -p "$dir/scripts" "$dir/config/hypr"
    cp "$ROOT/scripts/check.sh" "$dir/scripts/check.sh"
    if [ "$mode" = repo ]; then
        printf 'return true\n' > "$dir/config/hypr/hyprland.lua"
        printf 'return true\n' > "$dir/config/hypr/colors.lua"
    else
        printf 'return true\n' > "$dir/hyprland.lua"
        printf 'return true\n' > "$dir/config/window-effects.lua"
        # Decoy: an autogenerated config/ override must not be chosen.
        printf 'return true\n' > "$dir/config/hypr/hyprland.lua"
    fi
}

run_check() { # <layout dir> <log> <stdout file>
    HYPR_TEST_LOG="$2" PATH="$BIN:$PATH" bash "$1/scripts/check.sh" >"$3" 2>&1
    echo $?
}

REPO="$TMP/repo"
DEP="$TMP/dep"
setup_layout "$REPO" repo
setup_layout "$DEP" deployed

log="$TMP/repo.log"; out="$TMP/repo.out"; : > "$log"
rc="$(run_check "$REPO" "$log" "$out")"
[ "$rc" = 0 ] && ok "repo layout exits 0" || bad "repo layout exit $rc"
grep -q 'Hyprland: config OK' "$out" && ok "repo layout verifies the config" || bad "repo layout output"
[ "$(cat "$log")" = "$REPO/config/hypr/hyprland.lua" ] \
    && ok "repo layout uses config/hypr/hyprland.lua" \
    || bad "repo layout used $(cat "$log")"

log="$TMP/dep.log"; out="$TMP/dep.out"; : > "$log"
rc="$(run_check "$DEP" "$log" "$out")"
[ "$rc" = 0 ] && ok "deployed layout exits 0" || bad "deployed layout exit $rc"
grep -q 'Hyprland: config OK' "$out" && ok "deployed layout verifies the config" || bad "deployed layout output"
[ "$(cat "$log")" = "$DEP/hyprland.lua" ] \
    && ok "deployed layout uses the root hyprland.lua (not the config/ decoy)" \
    || bad "deployed layout used $(cat "$log")"

printf 'FAIL\n' > "$DEP/hyprland.lua"
log="$TMP/fail.log"; out="$TMP/fail.out"; : > "$log"
rc="$(run_check "$DEP" "$log" "$out")"
[ "$rc" != 0 ] && ok "verify failure propagates a non-zero exit" || bad "verify failure returned 0"
grep -q 'Hyprland --verify-config FAIL' "$out" \
    && ok "verify failure is reported" \
    || bad "verify failure output"

# Missing Hyprland: a PATH with the required tools but no Hyprland binary.
printf 'return true\n' > "$DEP/hyprland.lua"
TOOLS="$TMP/tools"
mkdir -p "$TOOLS"
for t in bash find luac mktemp sed sort id dirname rm cat mkdir; do
    p="$(command -v "$t" 2>/dev/null)" && ln -sf "$p" "$TOOLS/$t"
done
out="$TMP/skip.out"
PATH="$TOOLS" bash "$DEP/scripts/check.sh" >"$out" 2>&1
rc=$?
[ "$rc" = 0 ] && ok "missing Hyprland exits 0" || bad "missing Hyprland exit $rc"
grep -q 'Hyprland: SKIP' "$out" \
    && ok "missing Hyprland is reported as SKIP" \
    || bad "missing Hyprland output: $(tail -2 "$out")"

[ "$fail" = 0 ] && echo "CHECK.SH TEST: OK"
exit "$fail"
